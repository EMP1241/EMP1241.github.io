# Scientific chart: plot the recorded values without rerunning the experiment.
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.ticker import MultipleLocator, FormatStrFormatter
plt.rcParams.update({'font.family':'DejaVu Sans','font.size':17,'text.color':INK,'axes.labelcolor':MUTED,'xtick.color':MUTED,'ytick.color':MUTED,'svg.fonttype':'none'})
d=DATA['precision_experiment']; x=[n/1e6 for n in d['runs_per_comparison']]; y=d['maximum_probability_margin_percentage_points']
fig,ax=plt.subplots(figsize=(14,9),dpi=120,facecolor=BG)
fig.subplots_adjust(left=.12,right=.96,top=.73,bottom=.33)
ax.set_facecolor(BG); ax.spines[['top','right']].set_visible(False)
for side in ['left','bottom']: ax.spines[side].set_color('#36515b')
ax.grid(axis='y',alpha=.16); ax.plot(x,y,color=ACCENT,lw=3,marker='o',ms=10)
ax.axhline(.1,color='#e9bd77',ls='--',lw=2)
ax.set_ylim(0,.18); ax.set_xlim(.75,4.25); ax.set_xticks([1,2,4]); ax.yaxis.set_major_locator(MultipleLocator(.05)); ax.yaxis.set_major_formatter(FormatStrFormatter('%.2f'))
ax.set_xlabel('Simulation runs per comparison (millions)',labelpad=15)
ax.set_ylabel('Maximum probability margin\n(percentage points)',labelpad=16)
for xx,yy,label in zip(x,y,['0.141 · Continue','0.106 · Continue','0.077 · Target met']):
    ax.annotate(label,(xx,yy),xytext=(0,22 if xx<4 else -34),textcoords='offset points',ha='center',fontsize=17,color=INK)
fig.text(.06,.90,'COMPLETED NUMERICAL EXPERIMENT / OCTOBER 14, 2026',color=ACCENT,fontsize=14,weight='bold')
fig.text(.06,.83,'More trials reduced simulation sampling noise.',fontsize=25,weight='bold')
fig.text(.06,.18,'Dashed line: preset maximum of 0.1 percentage points.',color='#e9bd77',fontsize=17)
fig.text(.06,.12,'4 million runs per comparison × 16 comparisons = 64 million runs.',fontsize=18)
fig.text(.06,.055,'Recorded maximum across 32 fixed metrics. Measures numerical precision, not real-world location accuracy.',fontsize=12,color=MUTED)
fig.savefig(OUT/'nwsw-precision.png',facecolor=BG)
plt.close(fig)
print('Built six evidence panels and captured public example output.')
