"""Render public evidence panels from aggregate receipts and a runnable example.

No private research files are read. Example output is generated by running the
published script; the NWSW inputs are the selected aggregate record in assets.
"""
from pathlib import Path
from html import escape
import json
import subprocess
import sys
import textwrap

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'assets/evidence'
OUT.mkdir(exist_ok=True)
DATA = json.loads((ROOT/'assets/documents/nwsw-output-summary.json').read_text())
BG, PANEL, INK, MUTED, ACCENT = '#0b151b', '#13252e', '#f1f4ef', '#b3c6cc', '#72d7c9'

def text(x, y, value, size=26, color=INK, weight=400, family='Arial, sans-serif'):
    return f'<text xml:space="preserve" x="{x}" y="{y}" fill="{color}" font-family="{family}" font-size="{size}" font-weight="{weight}">{escape(value)}</text>'

def lines(x,y,value,width=65,size=26,color=MUTED,step=38):
    return ''.join(text(x,y+i*step,line,size,color) for i,line in enumerate(textwrap.wrap(value,width)))

def panel(name,kicker,title,subtitle,body,footer):
    svg=f'''<svg xmlns="http://www.w3.org/2000/svg" width="1400" height="900" viewBox="0 0 1400 900" role="img" aria-labelledby="title desc">
<title id="title">{escape(title)}</title><desc id="desc">{escape(subtitle+' '+footer)}</desc>
<rect width="1400" height="900" fill="{BG}"/><path d="M60 55H1340" stroke="{ACCENT}" stroke-width="3"/>
{text(60,105,kicker.upper(),20,ACCENT,700)}{text(60,175,title,46,INK,700)}
{lines(60,225,subtitle,90,25)}{body}
<path d="M60 794H1340" stroke="#36515b"/>{lines(60,837,footer,112,21,step=29)}</svg>'''
    (OUT/name).write_text(svg,encoding='utf-8')

example=ROOT/'assets/examples/handoff-integrity'
code=(example/'verify.py').read_text(encoding='utf-8').split('# BEGIN PUBLIC EXCERPT\n')[1].split('# END PUBLIC EXCERPT')[0].strip()
normal=subprocess.run([sys.executable,'verify.py'],cwd=example,capture_output=True,text=True,check=True).stdout.strip()
tested=subprocess.run([sys.executable,'verify.py','--self-test'],cwd=example,capture_output=True,text=True,check=True).stdout.strip()
(OUT/'integrity-example-output.txt').write_text('$ python verify.py\n'+normal+'\n\n$ python verify.py --self-test\n'+tested+'\n',encoding='utf-8')
body=f'<rect x="60" y="290" width="1280" height="438" rx="16" fill="{PANEL}"/>'
for i,line in enumerate(code.splitlines()):
    body+=text(90,343+i*32,line,22,INK,400,'Consolas, monospace')
panel('ra-code.svg','01 / Code · public runnable example','Check whether the delivered file changed.','This Python function compares a file’s SHA-256 fingerprint with the expected fingerprint.',body,'Standalone synthetic teaching example. The download includes this exact function and the full verifier.')
body=f'<rect x="60" y="290" width="1280" height="250" rx="16" fill="{PANEL}"/>'
body+=text(90,345,'$ python verify.py',30,ACCENT,700,'Consolas, monospace')
for i,line in enumerate(normal.splitlines()): body+=text(90,405+i*40,line,24,INK,400,'Consolas, monospace')
body+=text(60,610,'Run the downloaded example locally.',32,INK,700)
body+=lines(60,665,'Python 3.10 or newer. No additional packages. The sample contains two synthetic files and their expected fingerprints.',90,26)
panel('ra-running.svg','02 / Run · captured command output','Two files. One integrity check.','The intact public sample was run to produce the output shown below.',body,'Actual output from the published synthetic example, typeset for readability.')
body=''
checks=[line.removeprefix('PASS: ') for line in tested.splitlines() if line.startswith('PASS: ')]
assert len(checks)==5, tested
for i,line in enumerate(checks):
    y=285+i*90
    body+=f'<rect x="60" y="{y}" width="1280" height="74" rx="12" fill="{PANEL}"/>'
    body+=text(85,y+48,'PASS',24,ACCENT,700)+text(210,y+48,line[0].upper()+line[1:],28)
panel('ra-results.svg','03 / Results · actual self-test output','Changed, missing, and malformed files are caught.','python verify.py --self-test · Changes are made only in temporary copies.',body,'Integrity checks detect file differences against a trusted manifest; they do not establish scientific truth.')

body=''
